const REWARDS = {
  green:  { coins: 10, gems: 0 },
  yellow: { coins: 20, gems: 2 },
  red:    { coins: 40, gems: 5 },
};

function pickFive(level) {
  const pool = RIDDLES[level] || RIDDLES.green;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(5, shuffled.length));
}

